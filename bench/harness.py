#!/usr/bin/env python3
"""Reproducible benchmark + fault-injection harness for the Raft KV store.

    python3 bench/harness.py run                    # build the working tree, run everything
    python3 bench/harness.py run --ref HEAD~3       # benchmark an older commit (for before/after)
    python3 bench/harness.py run --quick            # ~1 minute smoke run
    python3 bench/harness.py compare A.json B.json  # before/after table
    python3 bench/harness.py report A.json          # re-render one result as Markdown

Results land in bench/results/<label>.json (+ .md) with the commit, host and exact command,
so every number can be regenerated by anyone with the repo.
"""

from __future__ import annotations

import argparse
import asyncio
import datetime as dt
import json
import os
import platform
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import report  # noqa: E402
from scenarios import SCENARIOS, Env  # noqa: E402

BENCH = Path(__file__).resolve().parent
REPO = BENCH.parent
CACHE = BENCH / ".cache"


def git(*args: str, cwd: Path = REPO) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def find_toolchain(explicit: str | None) -> str | None:
    if explicit:
        return explicit
    if os.environ.get("CMAKE_TOOLCHAIN_FILE"):
        return os.environ["CMAKE_TOOLCHAIN_FILE"]
    if os.environ.get("VCPKG_ROOT"):
        return str(Path(os.environ["VCPKG_ROOT"]) / "scripts/buildsystems/vcpkg.cmake")
    cache = REPO / "build" / "CMakeCache.txt"
    if cache.exists():
        m = re.search(r"^CMAKE_TOOLCHAIN_FILE:FILEPATH=(.+)$", cache.read_text(), re.M)
        if m:
            return m.group(1)
    return None


def build(ref: str | None, toolchain: str | None, build_type: str) -> tuple[Path, str, bool]:
    """Build `server` for `ref` (or the working tree). Returns (binary, sha, dirty)."""
    if ref:
        sha = git("rev-parse", "--verify", f"{ref}^{{commit}}")
        src = CACHE / f"src-{sha[:12]}"
        if not src.exists():
            src.mkdir(parents=True)
            archive = subprocess.Popen(["git", "archive", sha], cwd=REPO, stdout=subprocess.PIPE)
            subprocess.run(["tar", "-x", "-C", str(src)], stdin=archive.stdout, check=True)
            archive.wait()
        build_dir, dirty = CACHE / f"build-{sha[:12]}-{build_type}", False
    else:
        sha = git("rev-parse", "HEAD")
        dirty = bool(git("status", "--porcelain", "--", "src", "include", "CMakeLists.txt"))
        src, build_dir = REPO, CACHE / f"build-worktree-{build_type}"

    configure = ["cmake", "-S", str(src), "-B", str(build_dir), f"-DCMAKE_BUILD_TYPE={build_type}"]
    if shutil.which("ninja"):
        configure += ["-G", "Ninja"]
    if toolchain:
        configure.append(f"-DCMAKE_TOOLCHAIN_FILE={toolchain}")
    if not (build_dir / "CMakeCache.txt").exists():
        subprocess.run(configure, check=True, stdout=subprocess.DEVNULL)
    subprocess.run(["cmake", "--build", str(build_dir), "--target", "server"], check=True,
                   stdout=subprocess.DEVNULL)
    return build_dir / "server", sha, dirty


def cmd_run(args: argparse.Namespace) -> None:
    if args.bin:
        binary, sha = Path(args.bin).resolve(), git("rev-parse", "HEAD")
        dirty = bool(git("status", "--porcelain", "--", "src", "include"))
    else:
        print(f"Building {args.ref or 'working tree'} ({args.build_type})...", flush=True)
        binary, sha, dirty = build(args.ref, find_toolchain(args.toolchain), args.build_type)

    names = args.scenarios.split(",") if args.scenarios else list(SCENARIOS)
    unknown = set(names) - set(SCENARIOS)
    if unknown:
        sys.exit(f"unknown scenario(s): {', '.join(sorted(unknown))}")

    stamp = dt.datetime.now().astimezone()
    label = args.label or f"{stamp:%Y%m%d-%H%M%S}-{sha[:7]}{'-dirty' if dirty else ''}"
    scratch = Path(tempfile.mkdtemp(prefix="kvbench-"))
    env = Env(binary=binary, nodes=args.nodes, base_port=args.base_port, scratch=scratch,
              quick=args.quick, seed=args.seed, failover_writers=args.failover_writers)

    results, t0 = {}, time.monotonic()
    try:
        for name in names:
            print(f"[{name}] running...", flush=True)
            ts = time.monotonic()
            try:
                results[name] = asyncio.run(SCENARIOS[name](env))
                print(f"[{name}] done in {time.monotonic() - ts:.1f}s", flush=True)
            except Exception as e:  # record and keep going; the check table shows it as FAIL
                results[name] = {"error": f"{type(e).__name__}: {e}"}
                print(f"[{name}] ERROR after {time.monotonic() - ts:.1f}s: {e}", flush=True)
    finally:
        if args.keep_logs:
            print(f"Node logs and AOFs kept in {scratch}")
        else:
            shutil.rmtree(scratch, ignore_errors=True)

    result = {
        "meta": {
            "label": label,
            "git_sha": sha,
            "git_ref": args.ref or "working-tree",
            "git_dirty": dirty,
            "build_type": "prebuilt" if args.bin else args.build_type,
            "nodes": args.nodes,
            "quick": args.quick,
            "seed": args.seed,
            "failover_writers": args.failover_writers,
            "timestamp": stamp.isoformat(timespec="seconds"),
            "wall_seconds": round(time.monotonic() - t0, 1),
            "command": "python3 bench/harness.py " + shlex.join(sys.argv[1:]),
            "host": {"platform": platform.platform(), "machine": platform.machine(),
                     "cpu_count": os.cpu_count(), "python": platform.python_version()},
        },
        "scenarios": results,
    }
    result["checks"] = report.checks(result)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{label}.json").write_text(json.dumps(result, indent=2) + "\n")
    md = report.render(result)
    (out / f"{label}.md").write_text(md)
    print("\n" + md)
    print(f"Saved {out / label}.json and .md")
    if args.strict and any(c["passed"] is False for c in result["checks"]):
        sys.exit(1)


def cmd_compare(args: argparse.Namespace) -> None:
    before, after = (json.loads(Path(p).read_text()) for p in (args.before, args.after))
    md = report.compare(before, after)
    if args.out:
        Path(args.out).write_text(md)
    print(md)


def cmd_report(args: argparse.Namespace) -> None:
    print(report.render(json.loads(Path(args.result).read_text())))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    run = sub.add_parser("run", help="build, benchmark and fault-test a cluster")
    src = run.add_mutually_exclusive_group()
    src.add_argument("--ref", help="git commit/branch/tag to build (default: working tree)")
    src.add_argument("--bin", help="use an already-built server binary")
    run.add_argument("--nodes", type=int, default=3, help="cluster size (default 3)")
    run.add_argument("--scenarios", help=f"comma-separated subset of: {','.join(SCENARIOS)}")
    run.add_argument("--quick", action="store_true", help="shorter durations and fewer trials")
    run.add_argument("--label", help="result file name (default: <timestamp>-<sha>)")
    run.add_argument("--out", default=str(BENCH / "results"), help="output directory")
    run.add_argument("--base-port", type=int, default=18000)
    run.add_argument("--seed", type=int, default=42)
    run.add_argument("--failover-writers", type=int, default=32,
                     help="concurrent writers while the leader is killed (default 32)")
    run.add_argument("--build-type", default="Release")
    run.add_argument("--toolchain", help="CMake toolchain file (default: auto-detect vcpkg)")
    run.add_argument("--keep-logs", action="store_true", help="keep node logs/AOFs for inspection")
    run.add_argument("--strict", action="store_true", help="exit 1 if any correctness check fails")
    run.set_defaults(func=cmd_run)

    cmp_ = sub.add_parser("compare", help="before/after table for two result files")
    cmp_.add_argument("before")
    cmp_.add_argument("after")
    cmp_.add_argument("--out", help="also write the Markdown here")
    cmp_.set_defaults(func=cmd_compare)

    rep = sub.add_parser("report", help="render a result file as Markdown")
    rep.add_argument("result")
    rep.set_defaults(func=cmd_report)

    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
